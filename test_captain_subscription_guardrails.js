const assert = require('node:assert/strict');
const fs = require('node:fs');

const source = fs.readFileSync('server.js', 'utf8');
const eligibility = source.slice(source.indexOf('function weeklyChargeEligibleCaptains'), source.indexOf('function ammanDateKey'));

assert.match(source, /const CAPTAIN_SUBSCRIPTION_CENTS = 100/);
assert.match(source, /const CAPTAIN_SUBSCRIPTION_START = "2026-09-18T00:00:00\.000Z"/);
assert.match(source, /const CAPTAIN_SUBSCRIPTION_PERIOD_DAYS = 7/);
assert.match(source, /const CAPTAIN_SUBSCRIPTION_CHARGES_ENABLED = false/);
assert.match(source, /CREATE TABLE IF NOT EXISTS captain_subscription_charges/);
assert.match(source, /UNIQUE\(user_id, period_start\)/);
assert.match(source, /role='captain' AND active=1 AND is_bot=0 AND account_status='active'/);
assert.match(source, /u\.archived_at IS NULL/);
assert.match(source, /function manualWeeklyChargeEligibleCaptains\(stamp = now\(\)\)/);
assert.doesNotMatch(source, /wallet_cents>=\?/, 'weekly subscription eligibility must not require a positive balance');
assert.doesNotMatch(source, /ammanDateKey\(captain\.created_at\) < today/, 'new captains are not excluded by registration date');
assert.match(source, /function updateOfficialGroupAdminSnapshot\(groupId, snapshot\)/);
assert.match(source, /function officialGroupAdminSnapshotReady\(\)/);
assert.match(source, /function isOfficialGroupAdminPhone\(phone\)/);
assert.match(source, /!isOfficialGroupAdminPhone\(captain\.phone\)/);
assert.match(eligibility, /configuredRuntimeGroupId\(\)/);
assert.match(eligibility, /isConfiguredGroup\(officialGroupId\)/);
assert.match(eligibility, /c\.group_id=\?/);
assert.match(eligibility, /c\.status IN \('candidate','pending','finalized'\)/);
assert.match(eligibility, /p\.status IN \('open','accepted','completed'\)/);
assert.match(eligibility, /o\.accepted_at>=\? AND o\.accepted_at<\?/);
assert.match(eligibility, /o\.accepted_message_id IS NOT NULL/);
assert.match(eligibility, /c\.final_order_id=o\.id AND c\.status='finalized'/);
assert.match(eligibility, /JOIN order_settlements s ON s\.order_id=o\.id AND s\.status='applied'/);
assert.match(eligibility, /o\.status IN \('accepted','completed'\)/);
assert.doesNotMatch(eligibility, /COALESCE\(o\.updated_at,o\.created_at\)/, 'message edits or generic order updates are not activity');
assert.doesNotMatch(eligibility, /JOIN orders o ON o\.captain_user_id=u\.id/, 'acceptance requires a linked final settled order');
assert.match(source, /function ensureCaptainSubscriptionActivityPolicyStart\(\)/);
assert.match(source, /captain_weekly_activity_policy_start_v1/);
assert.match(source, /periodEndMs <= policyStartMs/);
assert.match(source, /return \{ start: completedWeek\.start, end: currentWeek\.start \}/);
const schedulerInit = source.indexOf('const weeklySubscriptionScheduler = createWeeklySubscriptionScheduler');
const policyInit = source.indexOf('ensureCaptainSubscriptionActivityPolicyStart();', schedulerInit);
assert.ok(schedulerInit >= 0 && policyInit > schedulerInit, 'policy start is persisted during module initialization before requests are served');
assert.match(source, /deferred_group_admin_snapshot/);
assert.match(source, /"skipped_debt_limit"/);
assert.match(source, /nextBalance < CAPTAIN_MIN_BALANCE_CENTS/);
assert.match(source, /activityScope/);
assert.match(source, /"subscription_fee"/);
assert.match(source, /function startCaptainSubscriptionScheduler\(\)/);
assert.match(source, /!manual && !CAPTAIN_SUBSCRIPTION_CHARGES_ENABLED/);
assert.match(source, /startCaptainSubscriptionScheduler\(\);/);
assert.match(source, /app\.get\("\/api\/admin\/subscriptions", requireAdmin/);
assert.match(source, /currentBalance: money\(row\.wallet_cents\)/);
assert.match(source, /const CAPTAIN_DAILY_CHARGE_CENTS = 10/);
assert.match(source, /CREATE TABLE IF NOT EXISTS captain_daily_charges/);
assert.match(source, /UNIQUE\(user_id, charge_date\)/);
assert.match(source, /function applyCaptainDailyCharges\(stamp = now\(\)\)/);
assert.match(source, /"daily_captain_charge"/);
assert.match(source, /DAILY-CAPTAIN-\$\{chargeDate\}-\$\{captain\.id\}/);
assert.match(source, /setInterval\(\(\) => applyCaptainDailyCharges\(\), CAPTAIN_DAILY_CHARGE_INTERVAL_MS\)/);
assert.match(source, /const CAPTAIN_DAILY_CHARGE_ENABLED = false/);
assert.doesNotMatch(source, /CAPTAIN_DAILY_CHARGE_ENABLED = process\.env/);
assert.match(source, /if \(CAPTAIN_DAILY_CHARGE_ENABLED\) \{/);
