const assert = require('node:assert/strict');
const fs = require('node:fs');
const server = fs.readFileSync('server.js', 'utf8');
const owner = fs.readFileSync('public/index.html', 'utf8');
const captain = fs.readFileSync('public/captain.html', 'utf8');
assert.match(server, /const COMPANY_BRAND_NAME = "العزوة"/);
assert.match(server, /const COMPANY_BRAND_ENGLISH = "ALEZWA"/);
assert.match(server, /`┃ \$\{COMPANY_BRAND_NAME\} \| بوابة التشغيل الرسمية`/);
assert.match(owner, /العزوة/);
assert.match(captain, /العزوة/);
assert.doesNotMatch(server, new RegExp('وصل' + 'ني'));
assert.doesNotMatch(owner, new RegExp('وصل' + 'ني'));
assert.doesNotMatch(captain, new RegExp('وصل' + 'ني'));
assert.doesNotMatch(server, /شركة الجراح/);
assert.doesNotMatch(owner, /شركة الجراح/);
assert.doesNotMatch(captain, /<strong>الجراح<\/strong>/);
console.log('Ezzwa branding guardrails verified');
