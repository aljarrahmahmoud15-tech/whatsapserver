const assert = require('node:assert/strict');
const fs = require('node:fs');
const server = fs.readFileSync('server.js', 'utf8');

assert.match(server, /async function notifyCaptainInsufficientAcceptanceBalance/);
assert.match(server, /deletionStatus === "paused"/);
assert.match(server, /تم رفض قبول «تم» لعدم كفاية الرصيد؛ سيبقى ردك ظاهرًا مؤقتًا ولن يُعتمد الحجز/);
assert.match(server, /تم حذف\/رفض رسالة «تم» لأن رصيد محفظتك لا يغطي عمولة هذا الطلب/);
assert.match(server, /الرصيد الحالي: \$\{money\(balanceCents\)\} JOD/);
assert.match(server, /العمولة المطلوبة: \$\{money\(requiredCents\)\} JOD/);
assert.match(server, /CAPTAIN-ACCEPTANCE-BALANCE-\$\{sourceKey\}/);
assert.match(server, /captain\.acceptance\.insufficient_balance/);
assert.match(server, /async function notifyOfficialGroupInsufficientAcceptanceDeletionFailure/);
assert.match(server, /GROUP-ACCEPTANCE-ALERT-TEXT-\$\{sourceKey\}/);
assert.match(server, /order\.acceptance\.insufficient_balance_deletion_failed/);
const helperStart = server.indexOf('async function notifyOfficialGroupInsufficientAcceptanceDeletionFailure');
const helperEnd = server.indexOf('\nconst cancellationPartyNotificationInFlight', helperStart);
assert.ok(helperStart >= 0 && helperEnd > helperStart);
const groupHelper = server.slice(helperStart, helperEnd);
const messageStart = groupHelper.indexOf('  const message = [');
const messageEnd = groupHelper.indexOf('  ].join("\\n");', messageStart);
assert.ok(messageStart >= 0 && messageEnd > messageStart);
const groupMessage = groupHelper.slice(messageStart, messageEnd);
assert.match(groupMessage, /⚠️ لم يُثبَّت الحجز لعدم كفاية الرصيد\./);
assert.match(groupMessage, /رقم الرحلة: \$\{String\(sourceKey\)\}/);
assert.doesNotMatch(groupMessage, /downloaderName|executorName|money\(priceCents\)|money\(requiredCents\)|origin|destination/);
const guardIndex = server.indexOf('if (acceptanceResult.state === "insufficient_balance")');
const deleteIndex = server.indexOf('deleteAcceptanceOnlyAfterGroupAlert({', guardIndex);
const notifyIndex = server.indexOf('await notifyCaptainInsufficientAcceptanceBalance(', guardIndex);
assert.ok(guardIndex >= 0 && deleteIndex > guardIndex && notifyIndex > deleteIndex, 'private notification runs after the deletion attempt');
const deleteHelperStart = server.indexOf('async function deleteAcceptanceOnlyAfterGroupAlert(');
const correctionIndex = server.indexOf('await notifyOfficialGroupInsufficientAcceptanceDeletionFailure(', deleteHelperStart);
const helperDeleteIndex = server.indexOf('await deleteWhatsAppMessageForEveryone(messageId, {', deleteHelperStart);
assert.ok(correctionIndex >= 0 && helperDeleteIndex > correctionIndex, 'group alert runs before the guarded deletion');
assert.match(server, /const alertConfirmed = Boolean\(correction && \["sent", "already_sent"\]\.includes\(correction\.status\)\)/);
assert.match(server, /sendWhatsAppAtMostOnce\(targetGroupId, message, undefined, 20000\)/);
assert.match(server, /serializedMessageId\(result\?\.message\)/);
console.log('insufficient balance rejection sends a compact group notice and deletes only the linked «تم» message');
