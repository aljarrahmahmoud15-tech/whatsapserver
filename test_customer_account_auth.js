const assert = require('node:assert/strict');
const fs = require('node:fs');
const server = fs.readFileSync('server.js', 'utf8');
const page = fs.readFileSync('public/book.html', 'utf8');
assert.match(server, /CREATE TABLE IF NOT EXISTS customer_accounts/);
assert.match(server, /CREATE TABLE IF NOT EXISTS customer_auth_challenges/);
assert.match(server, /app\.post\("\/api\/customer\/register"/);
assert.match(server, /app\.post\("\/api\/customer\/login"/);
assert.match(server, /app\.post\("\/api\/customer\/pin-recovery\/request-code"/);
assert.match(server, /app\.post\("\/api\/customer\/pin-recovery\/reset"/);
assert.match(server, /app\.post\("\/api\/customer\/change-pin"/);
assert.match(server, /app\.get\("\/api\/customer\/account", requireCustomer/);
assert.match(server, /customerAuthCodeHash\(customer\.phone, code\)/);
assert.match(server, /customer\.pin_recovered/);
assert.doesNotMatch(server, /audit\("customer\.pin_recovered"[^\n]*newPin/);
assert.match(page, /id="customer-register-btn"/);
assert.match(page, /id="customer-login-btn"/);
assert.match(page, /id="customer-forgot-btn"/);
assert.match(page, /\/api\/customer\/pin-recovery\/request-code/);
assert.match(page, /\/api\/customer\/pin-recovery\/reset/);
assert.match(page, /id="customer-change-pin-btn"/);
console.log('customer account authentication and WhatsApp PIN recovery guardrails verified');
