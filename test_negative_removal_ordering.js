const assert = require('node:assert/strict');
const fs = require('node:fs');
const server = fs.readFileSync('./server.js', 'utf8');
const thresholdStart = server.indexOf('async function enforceCaptainWalletThresholds(');
const thresholdEnd = server.indexOf('async function enforceCaptainWalletThresholdsForAll', thresholdStart);
assert.ok(thresholdStart >= 0 && thresholdEnd > thresholdStart);
const thresholdBody = server.slice(thresholdStart, thresholdEnd);
assert.match(server, /async function enforceConfirmedOrderDebtRemoval\(/);
assert.match(server, /negative_balance_removal_blocked/);
assert.match(server, /negative_notification_blocked/);
assert.match(server, /captain_removal_blocked_for_insufficient_balance/);
assert.match(server, /CAPTAIN_REMOVAL_PAUSED = true/);
assert.match(server, /policy: "no_debt_no_removal"/);
assert.doesNotMatch(server, /captain\.wallet\.negative_balance_allowed/);
assert.doesNotMatch(server, /policy: "allow_negative_balance_to_floor"/);
assert.doesNotMatch(thresholdBody, /suspendMemberForDebt\(/);
console.log('negative balance never removes, suspends, or disables a captain');
