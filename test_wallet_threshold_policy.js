const assert = require('node:assert/strict');
const fs = require('node:fs');
const server = fs.readFileSync('./server.js', 'utf8');
assert.match(server, /CAPTAIN_MIN_BALANCE_CENTS = Number\(process\.env\.CAPTAIN_MIN_BALANCE_CENTS \|\| 0\)/);
assert.match(server, /async function notifyCaptainLowBalance\(/);
assert.match(server, /async function enforceCaptainWalletThresholds\(/);
assert.match(server, /async function enforceCaptainWalletThresholdsForAll\(/);
assert.match(server, /policy: "no_debt_no_removal"/);
assert.match(server, /balance < CAPTAIN_MIN_BALANCE_CENTS/);
assert.match(server, /wallet_cents < 0/);
assert.match(server, /negativeBalanceAction: "negative balance is rejected/);
assert.match(server, /orderSettlementDebtPolicy: "projected balances below 0\.00 JOD are rejected/);
assert.match(server, /error: "الرصيد غير كافٍ"/);
const classify = (balanceCents, feeCents) => balanceCents - feeCents < 0 ? 'insufficient_balance' : 'allowed';
assert.equal(classify(99, 100), 'insufficient_balance');
assert.equal(classify(100, 100), 'allowed');
assert.equal(classify(-1, 1), 'insufficient_balance');
console.log('wallet zero-floor and no-removal policy verified');
