const assert = require('node:assert/strict');
const fs = require('node:fs');
const server = fs.readFileSync('server.js', 'utf8');

assert.match(server, /const INSUFFICIENT_BALANCE_ACCEPTANCE_DELETION_SETTING_KEY = "insufficient_balance_acceptance_deletion_enabled"/);
assert.match(server, /function insufficientBalanceAcceptanceDeletionEnabled\(\)/);
assert.match(server, /async function deleteAcceptanceMessagesForInsufficientBalance/);
const helperStart = server.indexOf('async function deleteAcceptanceMessagesForInsufficientBalance(');
const helperEnd = server.indexOf('\nasync function reopenOrderAfterInsufficientBalance', helperStart);
assert.ok(helperStart >= 0 && helperEnd > helperStart);
const helper = server.slice(helperStart, helperEnd);
assert.match(helper, /if \(!insufficientBalanceAcceptanceDeletionEnabled\(\)\)/);
assert.match(helper, /captainId/);
assert.match(helper, /deletedCount/);
assert.match(helper, /groupNotification: false/);
assert.match(server, /reopened_after_insufficient_balance/);

const groupStart = server.indexOf('const insufficientBalanceGroupNotificationInFlight = new Set();');
const groupEnd = server.indexOf('\nconst cancellationPartyNotificationInFlight', groupStart);
assert.ok(groupStart >= 0 && groupEnd > groupStart);
const groupHelper = server.slice(groupStart, groupEnd);
assert.match(groupHelper, /deletionStatus !== "deleted"/);
assert.match(groupHelper, /deletionResult\?\.ok !== true/);
assert.match(groupHelper, /deletionResult\?\.revoked !== true/);
assert.match(groupHelper, /deletionResult\?\.paused === true/);
assert.match(groupHelper, /return \{ status: "not_confirmed"/);
assert.doesNotMatch(groupHelper, /captain_private_only|official_group\.acceptance\.insufficient_balance_suppressed/);
assert.equal((server.match(/notifyCaptainInsufficientAcceptanceBalance/g) || []).length, 1);
assert.doesNotMatch(server, /acceptanceMessageDeleted/);
assert.doesNotMatch(server, /await notifyOfficialGroupOrderReopened\(/);
console.log('insufficient-balance deletion gate remains guarded; paused/partial/failed evidence cannot create a group notice');
